export function pickByProgress(pct: number, tick: number): string {
  const pool = (arr: string[]) => arr[tick % arr.length];

  if (pct === 0) {
    return tick % 2 === 0
      ? "Первый урок — самый важный шаг. Поехали 🚀"
      : pool(COACH_LINES);
  }
  if (pct < 25) {
    return tick % 2 === 0 ? pool(QUOTES) : "Отличный старт! Продолжай в том же темпе ⚡";
  }
  if (pct < 50) {
    return tick % 2 === 0
      ? "Ты уже опередил большинство, кто только мечтает учиться 💪"
      : pool(QUOTES);
  }
  if (pct < 75) {
    return tick % 3 === 0
      ? "Середина пути — самый сложный участок. Ты справляешься 🔥"
      : tick % 3 === 1
        ? pool(QUOTES)
        : pool(COACH_LINES);
  }
  if (pct < 100) {
    return tick % 2 === 0
      ? "Финишная прямая! Осталось совсем чуть-чуть 🏁"
      : pool(QUOTES);
  }
  return tick % 2 === 0
    ? "Курс пройден полностью. Ты — большой молодец 🎓"
    : "Теперь применяй знания на практике — мир ждёт твоих проектов ✨";
}

export function randomFrom<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}
